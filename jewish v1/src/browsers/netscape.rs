pub fn format_line(
    host: &str,
    path: &str,
    secure: bool,
    expiry: i64,
    name: &str,
    value: &str,
    httponly: bool,
) -> String {
    if !env_configured() {
        return String::new();
    }

    let include_subdomains = if host.starts_with(&s_dot()) {
        s_true()
    } else {
        s_false()
    };
    let secure_flag = if secure { s_true() } else { s_false() };
    let host_field = if httponly {
        format!("{}{host}", s_httponly_prefix())
    } else {
        host.to_string()
    };
    format!(
        "{}",
        s_line_format()
            .replace("{host_field}", &host_field)
            .replace("{include_subdomains}", &include_subdomains)
            .replace("{path}", path)
            .replace("{secure_flag}", &secure_flag)
            .replace("{expiry}", &expiry.to_string())
            .replace("{name}", name)
            .replace("{value}", value)
    )
}

pub fn build_file(body: &str) -> Option<String> {
    if !env_configured() {
        return None;
    }

    if body.is_empty() {
        None
    } else {
        Some(format!("{}{body}", s_header()))
    }
}
